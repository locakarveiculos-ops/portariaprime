import { test } from 'node:test';
import assert from 'node:assert/strict';
import { createDb } from './harness.mjs';

test('treinamento: fila independente após boas-vindas aceitas, sem retroativo ou duplicação', async () => {
  const db = await createDb();
  await db.sql('update plans set published = true');
  const owner = await db.createUser('owner@training.invalid', { name: 'Síndico Teste' });
  const resident = await db.createUser('resident@training.invalid', { name: 'Morador Teste' });
  const { tenant_id: tenant } = await db.rpc(owner, 'provision_tenant', { p_request_id: crypto.randomUUID(), p_name: 'Condomínio Treinamento', p_slug: 'treinamento', p_document: '11444777000161', p_timezone: 'America/Sao_Paulo', p_plan_code: 'prime', p_cycle: 'monthly' });
  const [{ id: unit }] = await db.sql("insert into units(tenant_id,block,label) values($1,'A','101') returning id", [tenant]);
  await db.sql("insert into tenant_memberships(tenant_id,user_id,role,status) values($1,$2,'morador','active')", [tenant,resident]);
  await db.sql("insert into unit_memberships(tenant_id,unit_id,user_id,status) values($1,$2,$3,'active')",[tenant,unit,resident]);
  const [{ id: req }] = await db.sql("insert into access_requests(tenant_id,user_id,full_name,unit_text,unit_id,phone,status) values($1,$2,'Morador Teste','101',$3,'5511988887777','approved') returning id",[tenant,resident,unit]);
  const insert = async (channel, approved, status='queued') => (await db.sql(`insert into notification_jobs(tenant_id,event,channel,recipient,ref_id,payload,status) values($1,'access_decision',$2,$3,$4,$5,$6) returning id`,[tenant,channel,channel==='email'?'resident@training.invalid':'5511988887777',req,{approved},status]))[0].id;
  const count = async () => (await db.sql("select count(*)::int n from notification_jobs where event='resident_training'"))[0].n;
  const source = await insert('whatsapp',true);
  assert.equal(await count(),0,'cadastro aprovado ainda sem envio das boas-vindas');
  await db.sql("update notification_jobs set status='failed' where id=$1",[source]);
  assert.equal(await count(),0,'falha das boas-vindas não dispara vídeo');
  await db.sql("update notification_jobs set status='accepted' where id=$1",[source]);
  assert.equal(await count(),1);
  const [video] = await db.sql("select * from notification_jobs where event='resident_training'");
  assert.equal(video.channel,'whatsapp'); assert.equal(video.recipient,'5511988887777'); assert.equal(video.ref_id,req);
  assert.equal(video.status,'queued');
  await db.sql("update notification_jobs set status='queued' where id=$1",[source]);
  await db.sql("update notification_jobs set status='accepted' where id=$1",[source]);
  assert.equal(await count(),1,'reprocessamento não duplica o vídeo');
  const email = await insert('email',true);
  await db.sql("update notification_jobs set status='accepted' where id=$1",[email]); assert.equal(await count(),1,'sem treinamento por e-mail');
  await db.sql("delete from notification_jobs where id=$1",[video.id]);
  await db.sql("update notification_jobs set status='queued',payload='{\"approved\":false}' where id=$1",[source]);
  await db.sql("update notification_jobs set status='accepted' where id=$1",[source]); assert.equal(await count(),0,'recusa nunca dispara vídeo');
  await db.sql("update notification_jobs set status='queued',payload='{\"approved\":true}' where id=$1",[source]);
  await db.sql("update notification_jobs set status='accepted' where id=$1",[source]);
  const [v] = await db.sql("select * from notification_jobs where event='resident_training'");
  const [allowed] = await db.service('select public.notification_is_authorized($1) ok',[v.id]); assert.equal(allowed.ok,true);
  const [{ ctx }] = await db.service('select public.notification_context($1) ctx',[v.id]);
  assert.equal(ctx.tenant_name,'Condomínio Treinamento'); assert.equal(ctx.resident.name,'Morador');
  await db.sql("update tenant_memberships set status='revoked' where tenant_id=$1 and user_id=$2",[tenant,resident]);
  assert.equal((await db.service('select public.notification_is_authorized($1) ok',[v.id]))[0].ok,false,'revogação bloqueia o vídeo antes do envio');
  const [grants] = await db.sql("select has_function_privilege('authenticated','public.notification_context(uuid)','execute') ctx, has_function_privilege('anon','app.enqueue_resident_training()','execute') trig");
  assert.equal(grants.ctx,false); assert.equal(grants.trig,false);
});
